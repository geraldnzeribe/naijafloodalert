  function t(lang) { return lang === "en" || !L[lang] ? L.en : Object.assign({}, L.en, L[lang]); }

  function message(lang, place, river, a) {
    const T = t(lang);
    if (!a || !a.level) return T.calm(place);
    const parts = [];
    if (a.river) parts.push(T.rise(river, a.first) + (a.peak ? T.peak(a.peak) : ""));
    if (a.rain7 != null && a.rain7 >= 100) parts.push(T.rain_heavy(Math.round(a.rain7)));
    const head = `${T.flood_word} – ${T.lvl[a.level].toUpperCase()} – ${place}: ${parts.join(T.and) || ""}.`;
    return `${head} ${T.act[a.level]} ${T.follow}`;
  }

